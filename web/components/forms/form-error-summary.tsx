"use client";

import { type FieldValues, type Path, useFormContext } from "react-hook-form";

import { cn } from "cn";
import { fill } from "@/lib/i18n/dictionaries";
import { useDictionary } from "@/lib/i18n/locale-provider";
import { resolveValidationMessage } from "@/lib/validation";

/**
 * The list of what to fix, when there is too much of it to see at once.
 *
 * Below four errors this does not appear: the messages are on the fields,
 * focus is already on the first one, and a summary would repeat what is
 * visible. Past that the form is taller than the screen, the errors are
 * scattered through it, and "nothing happened when I pressed save" is what
 * it looks like from the top.
 *
 * IT DOES NOT TAKE FOCUS. react-hook-form puts focus on the first invalid
 * field, which is where the correction starts; a summary that stole it
 * would make every failed submit begin with a list to read. It is announced
 * instead, through `role="alert"`, and its entries move focus on demand.
 *
 * Entries move focus by calling `setFocus` rather than by linking to an
 * anchor: the ids are generated by Base UI, and a link to an id this
 * component guesses is a link that silently stops working.
 */
export function FormErrorSummary<TValues extends FieldValues>({
  labels,
  threshold = 3,
  className,
}: {
  /** Field name to its label, so the list reads like the form. */
  labels: Partial<Record<Path<TValues>, string>>;
  /** Appears strictly past this many errors. */
  threshold?: number;
  className?: string;
}) {
  const t = useDictionary();
  const {
    formState: { errors },
    setFocus,
  } = useFormContext<TValues>();

  const entries = Object.entries(errors).filter(
    ([name]) => name !== "root" && name in labels,
  ) as [Path<TValues>, { message?: string }][];

  if (entries.length <= threshold) return null;

  return (
    <div
      role="alert"
      className={cn(
        "rounded-lg border border-shell-badge-foreground/30 bg-shell-badge/40 p-4",
        className,
      )}
    >
      <p className="text-sm font-medium text-shell-badge-foreground">
        {fill(t.forms.errorSummaryTitle, { count: entries.length })}
      </p>
      <ul className="mt-2 space-y-1">
        {entries.map(([name, error]) => (
          <li key={name}>
            <button
              type="button"
              onClick={() => setFocus(name)}
              className="text-start text-sm text-shell-badge-foreground underline underline-offset-4 outline-none focus-visible:ring-3 focus-visible:ring-brand-violet/40"
            >
              {labels[name]} : {resolveValidationMessage(t, error.message ?? "")}
            </button>
          </li>
        ))}
      </ul>
    </div>
  );
}
