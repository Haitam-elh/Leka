"""The agents' inventory (LEKA-454): the registry, the marketplace reference,
what is sold, at what price, what includes it, and how Stripe charges it —
one table, from the sources themselves, never typed by hand.

    python -m leka.capabilities.inventory --write   # docs/billing/agents-inventory.md

tests/test_agents_inventory.py fails when the committed file says
something else: what the sources say changes, the document follows.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

from leka.billing import Catalogue, catalogue
from leka.capabilities.definition import Kind
from leka.capabilities.registry import agents as registry_agents
from leka.core.config import settings

DOCUMENT = Path(__file__).resolve().parents[3] / "docs" / "billing" / "agents-inventory.md"


@dataclass(frozen=True)
class Row:
    """One agent, wherever it is known."""

    reference: str  # its name in the marketplace reference, or "—"
    category: str
    agent: str | None  # the registry's agent standing for it
    lifecycle: str | None
    tier: str | None
    price: int | None  # cents a month
    status: str  # on_sale, registry_only, not_built, unpriced
    included_in: tuple[str, ...]
    bundles: tuple[str, ...]


def _euros(cents: int | None) -> str:
    if cents is None:
        return "—"
    return f"{cents // 100} €" if cents % 100 == 0 else f"{cents / 100:.2f} €".replace(".", ",")


def rows(offer: Catalogue | None = None) -> list[Row]:
    """Every agent: the reference's, then the registry's it does not name."""
    sold = (offer or catalogue()).add_ons
    known = {d.key: d for d in registry_agents(settings.agents_dir) if d.kind is Kind.AGENT}

    def plans_of(key: str | None) -> tuple[str, ...]:
        """The least plan that includes it — and every one above."""
        first = sold.included_from(key) if key is not None else None
        return (f"{first} +",) if first else ()

    found: list[Row] = []
    for ref_key, ref in sold.reference.items():
        agent = sold.runtime_of(ref_key)
        tier = sold.agents[agent].tier if agent else ref.tier
        if agent is not None:
            # Sold as an option below the plan that includes it.
            status = "on_sale"
        else:
            status = "not_built" if ref.tier is not None else "unpriced"
        found.append(
            Row(
                reference=ref.name,
                category=ref.category,
                agent=agent,
                lifecycle=str(known[agent].lifecycle) if agent and agent in known else None,
                tier=tier,
                price=sold.tiers.get(tier) if tier else None,
                status=status,
                included_in=plans_of(agent),
                bundles=tuple(b.key for b in sold.bundles if ref_key in b.members),
            )
        )
    for key, definition in sorted(known.items()):
        if any(r.agent == key for r in found):
            continue
        on_sale = sold.agents.get(key)
        found.append(
            Row(
                reference="—",
                category=definition.category,
                agent=key,
                lifecycle=str(definition.lifecycle),
                tier=on_sale.tier if on_sale else None,
                price=sold.prices.get(key),
                status="on_sale" if on_sale else "registry_only",
                included_in=plans_of(key),
                bundles=(),
            )
        )
    return found


STATUS = {
    "on_sale": "Option payante, incluse dès le plan indiqué",
    "registry_only": "Registre seulement — jamais vendu",
    "not_built": "Référence seulement — non construit, jamais vendu",
    "unpriced": "Nommé par un bundle, absent de la liste — à arbitrer",
}


def markdown(offer: Catalogue | None = None) -> str:
    sold = (offer or catalogue()).add_ons
    lines = [
        "# Agents inventory (LEKA-454)",
        "",
        "Generated by `python -m leka.capabilities.inventory` from the registry "
        "(`agents/*/SKILL.md`), the commercial catalogue (`api/leka/billing/catalogue.yaml`) "
        "and the marketplace reference it records. Do not edit by hand: "
        "`tests/test_agents_inventory.py` fails when it differs.",
        "",
        "LEKA's own capabilities — understanding, the analysis, its answer (LEKA Assistant) — "
        "are every plan's: its fundamental agents, not listed here. Each agent and bundle is a "
        "Stripe product and monthly price made by `stripe-sync`, found by its lookup key "
        "(`leka_addon_<kind>_<key>_month_<cents>`), on a subscription of its own; "
        "an option is granted only once Stripe confirms its payment.",
        "",
        "## Agents",
        "",
        "| Reference | Category | Registry agent | Lifecycle | Tier | Price HT / month | "
        "Status | Included from | Bundles |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows(offer):
        lines.append(
            f"| {r.reference} | {r.category} | {f'`{r.agent}`' if r.agent else '—'} | "
            f"{r.lifecycle or '—'} | {r.tier or '—'} | {_euros(r.price)} | {STATUS[r.status]} | "
            f"{', '.join(r.included_in) or '—'} | {', '.join(r.bundles) or '—'} |"
        )
    lines += [
        "",
        "## Bundles",
        "",
        "| Bundle | Price HT / month | Members alone | Saving | Sold | Members not built |",
        "|---|---|---|---|---|---|",
    ]
    for b in sold.bundles:
        missing = ", ".join(sold.reference[m].name for m in b.missing) or "—"
        saving = f"{b.savings_percent} %" if b.savings_percent is not None else "not shown"
        lines.append(
            f"| {b.name.en} | {_euros(b.monthly_price)} | {_euros(b.alone_price)} | {saving} | "
            f"{'yes' if b.sellable else 'no'} | {missing} |"
        )
    lines += [
        "",
        "A bundle is sold once every member is an agent of the registry on sale; its saving is "
        "computed from its members' prices, and shown only when every member has one.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    if "--write" in sys.argv:
        DOCUMENT.write_text(markdown(), encoding="utf-8")
    else:
        sys.stdout.write(markdown())
