"""Column mixins shared by every table.

Architecture rule 2: every business table carries workspace_id NOT NULL with
a foreign key. LEKA is multi-tenant on shared tables, so a forgotten
workspace_id is not a missing column — it is one customer reading another
customer's incidents. WorkspaceScopedMixin exists so that column is never
written by hand and never forgotten.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column


class UUIDPrimaryKeyMixin:
    """A UUID primary key generated by the database.

    UUID rather than a sequence: identifiers travel between the API, the
    worker and the frontend, and a sequential integer tells every customer
    how many rows their neighbours have.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )


class TimestampMixin:
    """Creation and update timestamps, always timezone-aware.

    Defaults are computed by PostgreSQL, not by Python: the API, the worker
    and a psql session must agree on what "now" means.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


class WorkspaceScopedMixin(UUIDPrimaryKeyMixin, TimestampMixin):
    """id + workspace_id + created_at + updated_at.

    What every business table inherits. The workspaces table itself uses
    UUIDPrimaryKeyMixin and TimestampMixin directly — it cannot reference
    itself.

    ON DELETE CASCADE: removing a workspace removes the customer's data.
    That is the intended behaviour of an account deletion, and it keeps
    orphaned rows — rows belonging to no tenant — impossible by construction.
    """

    workspace_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
